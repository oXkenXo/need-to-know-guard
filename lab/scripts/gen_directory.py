"""Generate the directory (LDIF) and the mail-server alias file from company.yaml.

    python scripts/gen_directory.py
      -> build/directory.ldif            people + groups for OpenLDAP (passwords hashed, from seed/accounts.env)
      -> config/mail/postfix-virtual.cf  mailing lists + forwarding rules for docker-mailserver
      -> config/mail/postfix-accounts.cf mailboxes (same passwords as the directory)
"""
import base64
import hashlib
import os
import subprocess

import common as c

BUILD = c.LAB / "build"


def ssha(pw):
    salt = os.urandom(8)
    return "{SSHA}" + base64.b64encode(hashlib.sha1(pw.encode() + salt).digest() + salt).decode()


def ldif(pw):
    b = c.BASE_DN
    out = [f"dn: ou=people,{b}\nobjectClass: organizationalUnit\nou: people\n",
           f"dn: ou=groups,{b}\nobjectClass: organizationalUnit\nou: groups\n"]
    for p in c.C["people"]:
        first, last = p["name"].split(" ", 1)
        lines = [f"dn: uid={p['uid']},ou=people,{b}", "objectClass: inetOrgPerson", f"uid: {p['uid']}",
                 f"cn: {p['name']}", f"givenName: {first}", f"sn: {last}", f"displayName: {p['name']}",
                 f"mail: {p['uid']}@{c.DOMAIN}", f"title: {p['title']}",
                 f"departmentNumber: {c.C['departments'][p['dept']]['name']}",
                 f"employeeType: {'employee'}", f"description: joined {p['joined']}",
                 f"userPassword: {ssha(pw[p['uid']])}"]
        if p.get("manager"):
            lines.append(f"manager: uid={p['manager']},ou=people,{b}")
        out.append("\n".join(lines) + "\n")
    names = {d: v["name"] for d, v in c.C["departments"].items()}
    names.update({"all-staff": "All employees", "managers": "Department heads and executives"})
    for g, members in c.directory_groups().items():
        lines = [f"dn: cn={g},ou=groups,{b}", "objectClass: groupOfNames", f"cn: {g}", f"description: {names.get(g, g)}"]
        lines += [f"member: uid={m},ou=people,{b}" for m in members]
        out.append("\n".join(lines) + "\n")
    return "\n".join(out)


def sha512_crypt(pw):
    r = subprocess.run(["openssl", "passwd", "-6", "-stdin"], input=pw, capture_output=True, text=True, check=True)
    return "{SHA512-CRYPT}" + r.stdout.strip()


def postfix_accounts(pw):
    """docker-mailserver account file (same format as 'setup email add' writes). Mailboxes exist before the
    server starts, so it never waits for accounts."""
    return "".join(f"{u}@{c.DOMAIN}|{sha512_crypt(pw[u])}\n" for u in sorted(c.PEOPLE))


def postfix_virtual():
    groups = c.directory_groups()
    lines = ["# Generated by scripts/gen_directory.py from company.yaml — mailing lists and forwarding rules.",
             "# Format: <address> <recipient>[,<recipient>...]", ""]
    lines.append("# --- mailing lists")
    for name in c.C["mail_lists"]:
        members = c.list_members(name, groups)
        lines.append(f"{name}@{c.DOMAIN} " + ",".join(f"{m}@{c.DOMAIN}" for m in members))
    lines += ["", "# --- forwarding rules (the original mailbox keeps a copy)"]
    for f in c.C.get("mail_forwards") or []:
        lines.append(f"# since {f['since']}: {f['reason']}")
        lines.append(f"{f['from']}@{c.DOMAIN} {f['from']}@{c.DOMAIN},{f['to']}@{c.DOMAIN}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    BUILD.mkdir(exist_ok=True)
    pw = c.read_accounts()
    (BUILD / "directory.ldif").write_text(ldif(pw), encoding="utf-8")
    mail_cfg = c.LAB / "config" / "mail"
    mail_cfg.mkdir(parents=True, exist_ok=True)
    (mail_cfg / "postfix-virtual.cf").write_text(postfix_virtual(), encoding="utf-8")
    (mail_cfg / "postfix-accounts.cf").write_text(postfix_accounts(pw), encoding="utf-8")
    print("written: build/directory.ldif, config/mail/postfix-virtual.cf, config/mail/postfix-accounts.cf")
